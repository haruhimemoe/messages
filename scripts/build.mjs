/**
 * @file scripts/build.mjs
 * @desc Builds dist/ from messages/<locale>/<namespace>.json: one ES module per catalog
 *       (`export default {...}`) and an index whose loader map lists every catalog as a literal
 *       import(), so bundlers include each one without globs or import attributes. No
 *       dependencies.
 * @author David @dvhsh (https://dvh.sh)
 * @created Sun Oct 11, 2026
 * @modified Sun Oct 11, 2026
 */

import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
// Tests pass other folders: node scripts/build.mjs <source> <out>.
const SOURCE = process.argv[2] ?? join(ROOT, "messages");
const OUT = process.argv[3] ?? join(ROOT, "dist");
const DEFAULT = "en";
const NAME = /^[a-z][a-z0-9-]*$/;
const LOCALE = /^[a-z]{2,3}(?:-[A-Z][a-z]{3})?(?:-[A-Z]{2})?$/;

const locales = readdirSync(SOURCE, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort((a, b) => (a === DEFAULT ? -1 : b === DEFAULT ? 1 : a.localeCompare(b)));
if (locales[0] !== DEFAULT) throw new Error(`messages/${DEFAULT} is missing`);
for (const locale of locales) if (!LOCALE.test(locale)) throw new Error(`bad locale ${locale}`);

const namespacesOf = (locale) =>
  readdirSync(join(SOURCE, locale))
    .filter((file) => file.endsWith(".json"))
    .map((file) => file.slice(0, -5))
    .sort();
const namespaces = namespacesOf(DEFAULT);
for (const name of namespaces) if (!NAME.test(name)) throw new Error(`bad namespace ${name}`);

rmSync(OUT, { recursive: true, force: true });
const catalogs = {};
for (const locale of locales) {
  mkdirSync(join(OUT, locale), { recursive: true });
  catalogs[locale] = [];
  for (const name of namespacesOf(locale)) {
    if (!namespaces.includes(name))
      throw new Error(`${locale}/${name}.json has no ${DEFAULT} catalog`);
    const data = JSON.parse(readFileSync(join(SOURCE, locale, `${name}.json`), "utf8"));
    writeFileSync(join(OUT, locale, `${name}.js`), `export default ${JSON.stringify(data)};\n`);
    catalogs[locale].push(name);
  }
}

const map = locales
  .map(
    (locale) =>
      `  ${JSON.stringify(locale)}: {\n${catalogs[locale]
        .map((name) => `    ${JSON.stringify(name)}: () => import("./${locale}/${name}.js"),`)
        .join("\n")}\n  },`,
  )
  .join("\n");

writeFileSync(
  join(OUT, "index.js"),
  `// Generated by scripts/build.mjs. Edit messages/, not this file.

/** Every locale with at least one catalog, ${JSON.stringify(DEFAULT)} first. */
export const LOCALES = Object.freeze(${JSON.stringify(locales)});
/** Every namespace (one per ${DEFAULT} catalog). */
export const NAMESPACES = Object.freeze(${JSON.stringify(namespaces)});
/** The locale every other one falls back to, key by key. */
export const DEFAULT_LOCALE = ${JSON.stringify(DEFAULT)};

const CATALOGS = {
${map}
};

const isObject = (value) => typeof value === "object" && value !== null && !Array.isArray(value);
const merge = (base, over) => {
  const out = { ...base };
  for (const [key, value] of Object.entries(over)) {
    if (key === "__proto__" || key === "constructor" || key === "prototype") continue;
    out[key] = isObject(out[key]) && isObject(value) ? merge(out[key], value) : value;
  }
  return out;
};
const own = (object, key) => Object.hasOwn(object, key) ? object[key] : undefined;

export async function loadMessages(locale, namespace) {
  const base = own(CATALOGS[DEFAULT_LOCALE], namespace);
  if (!base) throw new Error(\`@haruhimemoe/messages: no namespace "\${namespace}"\`);
  const english = (await base()).default;
  const translated = locale === DEFAULT_LOCALE ? undefined : own(own(CATALOGS, locale) ?? {}, namespace);
  const catalog = translated ? merge(english, (await translated()).default) : english;
  return { [namespace]: catalog };
}

export const messagesLoader = (namespace) => (locale) => loadMessages(locale, namespace);
`,
);

writeFileSync(
  join(OUT, "index.d.ts"),
  `/** A catalog: nested objects of ICU message strings. */
export type Catalog = { [key: string]: string | Catalog };
/** Every locale with at least one catalog, "${DEFAULT}" first. */
export declare const LOCALES: readonly string[];
/** Every namespace. */
export declare const NAMESPACES: readonly (${namespaces.map((n) => JSON.stringify(n)).join(" | ")})[];
/** One of NAMESPACES. */
export type Namespace = (typeof NAMESPACES)[number];
/** The locale every other one falls back to, key by key. */
export declare const DEFAULT_LOCALE: "${DEFAULT}";
/**
 * One namespace for a locale, under its own key ({ packs: {...} }). Keys the locale lacks come
 * from ${DEFAULT}; an unknown locale gets ${DEFAULT}. Throws for an unknown namespace.
 */
export declare function loadMessages(locale: string, namespace: Namespace): Promise<Record<string, Catalog>>;
/** loadMessages for one namespace, shaped as next-kit's MessagesLoader. */
export declare const messagesLoader: (namespace: Namespace) => (locale: string) => Promise<Record<string, Catalog>>;
`,
);
console.log(`built ${locales.length} locale(s), ${namespaces.length} namespace(s)`);
